#В-2.Дано целое число А. Проверить истинность высказывания "Число А является нечетным"

while True:
    try:
        A = int(input("Введите число: "))
        if A % 2 == 1:
            print("Верно, Число A нечетное")
        else:
            print("Число A или нуль или четное")

    except ValueError:
        print("Нужно вводить целые числа")
