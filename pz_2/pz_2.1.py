#Вариант 2. Известно что X кг шок. конфет стоит A рублей, а Y ирисок B рублей.
#Выяснить сколько стоит 1кг шок. конфет ирисок, и во сколько раз шок. конфеты дороже ирисок

while True:
    try:
        X = list(float(input("Введите массу и цену шок. конфет через точку-запятую "))).split(";")
        Y = list(float(input("Введите массу и цену шок. ирисок через точку-запятую "))).split(";")

        for n in X and Y:
            if n <= 0:
                exit()
    except:
        print(X+Y)



